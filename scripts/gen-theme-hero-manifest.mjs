// Scans public/images/themes/ for {theme-id}-hero.jpg files and writes
// src/lib/theme-hero-manifest.ts listing which theme IDs have a hero image.
//
// Runs as the first step of `npm run build` (see package.json), so simply
// dropping a correctly-named image into public/images/themes/ and deploying
// is enough to wire it up — no source edit required.
//
// Naming convention:  public/images/themes/{theme-id}-hero.jpg   (1600x900)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname  = path.dirname(fileURLToPath(import.meta.url));
const themesDir  = path.join(__dirname, "..", "public", "images", "themes");
const outFile    = path.join(__dirname, "..", "src", "lib", "theme-hero-manifest.ts");

let ids = [];
try {
  ids = fs
    .readdirSync(themesDir)
    .filter((f) => f.endsWith("-hero.jpg"))
    .map((f) => f.replace(/-hero\.jpg$/, ""))
    .sort();
} catch {
  console.warn(`[gen-theme-hero-manifest] themes dir not found: ${themesDir}`);
}

const content = `// AUTO-GENERATED by scripts/gen-theme-hero-manifest.mjs — do not edit by hand.
// Lists theme IDs that have a hero image at public/images/themes/{id}-hero.jpg.
// Regenerated on every build.
export const THEME_HERO_IDS: readonly string[] = ${JSON.stringify(ids)};
`;

fs.writeFileSync(outFile, content);
console.log(`[gen-theme-hero-manifest] hero images: ${ids.join(", ") || "(none)"}`);
